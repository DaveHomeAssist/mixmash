// Front of House reference generator: writes docs/ASSETS.md, docs/CATALOG.md and docs/STRINGS.md.
//
// Run with `npm run docs:front-of-house`. Every table comes from the code (data.mjs, engine.mjs,
// board.js, game.js) or from the hand-kept asset register (sprites/manifest.mjs), so the documents
// cannot drift: CI regenerates them and fails if the committed copies differ. The script exits
// non-zero when the code and the register disagree (an unlisted image, a listed file that is
// missing, an action with no description), so a stale register fails the build too.

import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, resolve } from 'node:path';
import vm from 'node:vm';
import * as D from '../data.mjs';
import * as E from '../engine.mjs';
import { LOOK, SPRITE_FIT } from '../board.js';
import * as M from '../sprites/manifest.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..'); // front-of-house/
const REPO = resolve(ROOT, '..');
const DOCS = join(ROOT, 'docs');
const problems = [];
const problem = (msg) => problems.push(msg);

const HEADER = (title, what) => `# ${title}

*Generated by \`npm run docs:front-of-house\` (\`front-of-house/tools/docs.mjs\`). Do not edit by hand. CI regenerates
this file and fails if the committed copy differs. ${what}*
`;
const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (head, rows) => [
  `| ${head.join(' | ')} |`,
  `| ${head.map(() => '---').join(' | ')} |`,
  ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
].join('\n');
const usd = (n) => `$${Number(n).toLocaleString('en-US')}`;
const kb = (bytes) => `${(bytes / 1024).toFixed(1)}`;
const clockAt = (share) => {
  const m = 19 * 60 + Math.round(share * 240); // doors 19:00 to curfew 23:00, as game.js clock()
  return `${String(Math.floor(m / 60)).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}`;
};

// PNG width and height from the IHDR chunk, so the script needs no image library.
function pngSize(file) {
  const b = readFileSync(file);
  if (b.length < 24 || b.toString('ascii', 1, 4) !== 'PNG') return null;
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20), bytes: b.length };
}


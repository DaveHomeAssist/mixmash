// Every fail(state, …) call in a case: its argument (brackets balanced), the literal texts in it,
// and the action it is limited to when it sits under `if (action.type === '…' …)`.
function failCalls(seg) {
  const out = [];
  let from = 0;
  for (;;) {
    const at = seg.indexOf('fail(state, ', from);
    if (at < 0) break;
    let i = at + 'fail(state, '.length;
    const argStart = i;
    let depth = 1;
    let quote = null;
    for (; i < seg.length; i += 1) {
      const c = seg[i];
      if (quote) { if (c === quote && seg[i - 1] !== '\\') quote = null; continue; }
      if (c === "'" || c === '`' || c === '"') { quote = c; continue; }
      if (c === '(' || c === '[' || c === '{') depth += 1;
      if (c === ')' || c === ']' || c === '}') { depth -= 1; if (depth === 0) break; }
    }
    const arg = seg.slice(argStart, i).replace(/\s+/g, ' ').trim();
    from = i;
    if (arg === 'err') continue;
    const lineStart = seg.lastIndexOf('\n', at);
    const ifLine = seg.slice(seg.lastIndexOf('\n', lineStart - 1), lineStart);
    const only = (ifLine.match(/action\.type === '([A-Za-z]+)'/) || [])[1] || null;
    const literals = [...arg.matchAll(/'([^']*)'|`([^`]*)`/g)].map((x) => x[1] ?? x[2]);
    if (/^['`][^'`]*['`]$/.test(arg)) out.push({ text: literals[0], only });
    else if (FAIL_EXPLAIN[arg]) out.push({ text: FAIL_EXPLAIN[arg], computed: true, only });
    else if (/\?/.test(arg) && literals.length > 1) literals.forEach((t) => out.push({ text: t, only }));
    else { problem(`tools/docs.mjs cannot read the refusal \`${arg}\`; add it to FAIL_EXPLAIN`); }
  }
  return out;
}

// Split applyAction's switch into its cases and read each one's rules from the source.
function parseActions() {
  const src = readFileSync(join(ROOT, 'engine.mjs'), 'utf8');
  const start = src.indexOf('function applyActionCore(');
  const end = src.indexOf('\n}\n', start);
  const body = src.slice(start, end);
  const re = /\n {4}case '([A-Za-z]+)':/g;
  const marks = [];
  let m;
  while ((m = re.exec(body))) marks.push({ id: m[1], at: m.index });
  const defaultAt = body.indexOf('\n    default:');
  const actions = {};
  marks.forEach((mk, i) => {
    const seg = body.slice(mk.at, i + 1 < marks.length ? marks[i + 1].at : defaultAt);
    actions[mk.id] = {
      seg,
      need: [...seg.matchAll(/need\('([a-z]+)'\)/g)].map((x) => x[1]),
      to: [...new Set([...seg.matchAll(/s\.phase = '([a-z]+)'/g)].map((x) => x[1]))],
      fields: [...new Set([...seg.matchAll(/action\.([A-Za-z]+)/g)].map((x) => x[1]).filter((f) => f !== 'type'))],
      fails: failCalls(seg),
    };
  });
  // Cases that share a body (nextShow and retry) take the body of the case they fall into.
  for (const [id, a] of Object.entries(actions)) {
    if (!a.need.length && !a.to.length && !a.fails.length && a.seg.trim().split('\n').length <= 1) {
      const next = marks[marks.findIndex((x) => x.id === id) + 1];
      if (next) actions[id] = { ...actions[next.id], fallsInto: next.id };
    }
  }
  return actions;
}


// Run each action from a reference state in each phase and record what happens.
function transitionMatrix(actionIds) {
  const run = (s, list) => list.reduce((st, a) => {
    const r = E.applyAction(st, a);
    if (r.error) throw new Error(`reference path failed at ${a.type}: ${r.error}`);
    return r.state;
  }, s);
  const book = E.createGame(42);
  const build = run(book, [{ type: 'chooseDeal', deal: 'door' }, { type: 'setLayout', objects: D.STARTER_LAYOUT }]);
  const promote = run(build, [{ type: 'confirmBuild' }]);
  const show = run(promote, [{ type: 'confirmPromotion' }]);
  const firstResponse = D.INCIDENTS[show.show.incidentId].responses[0].id;
  const settle = run(show, [{ type: 'respond', responseId: firstResponse }]);
  const done = run(settle, [{ type: 'acceptSettlement' }]);
  const states = { book, build, promote, show, settle, done };
  const payload = {
    enableEquipment: {},
    equipment: { command: { id: 'reference_buy', kind: 'buy', family: 'small-pa' } },
    assignEquipment: { assetId: null },
    enableResearch: {},
    research: { command: { kind: 'start', project: 'patch' } },
    chooseDeal: { deal: 'door' },
    chooseVenue: { venueId: 'lot' },
    place: { object: { type: 'restroom', x: 5, y: 10, rot: 0 } },
    setLayout: { objects: D.STARTER_LAYOUT },
    remove: { index: 0 },
    confirmBuild: {},
    setPromotion: { price: 20 },
    confirmPromotion: {},
    chooseDoorCrew: { choice: 'gate' },
    advanceLive: { minute: 5 },
    assignLiveWorker: { station: 'gate' },
    respond: { responseId: firstResponse },
    acceptSettlement: {},
    back: {},
    nextShow: {},
    retry: {},
  };
  for (const id of actionIds) if (!payload[id]) problem(`tools/docs.mjs has no reference payload for action ${id}`);
  const rows = E.PHASES.map((phase) => [phase, ...actionIds.map((id) => {
    const r = E.applyAction(states[phase], { type: id, ...(payload[id] || {}) });
    if (r.error) return '✗';
    return r.state.phase === phase ? '✓' : `→ ${r.state.phase}`;
  })]);
  return { rows, firstResponse };
}

